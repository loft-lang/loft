// invocations are GENERATED by `build.rs` (via
// `loft-ffi-build::generate_register_from_loft_with_bridges`) scanning this
// crate's loft sources for `#native` annotations.
include!(concat!(env!("OUT_DIR"), "/loft_register_gen.rs"));
