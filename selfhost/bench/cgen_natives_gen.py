"""Write selfhost/src/cgen_natives.loft from the Rust generator's native tables.

@PLN91 strand 12 (doc/claude/plans/91-self-host/12-c-generator.md).  `native_c`,
`host_native_c` and `json_native_c` in src/c/mod.rs say which C runtime function implements a
standard-library native; the loft-written generator asks the same table.  While the Rust
generator is the oracle the table has one home there and this script writes the loft copy:

    python3 selfhost/bench/cgen_natives_gen.py           write the loft file
    python3 selfhost/bench/cgen_natives_gen.py --check   exit 1 when it is out of date
"""
import argparse, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "src", "c", "mod.rs")
OUT = os.path.join(ROOT, "selfhost", "src", "cgen_natives.loft")
TABLES = ["native_c", "host_native_c", "json_native_c"]


def arms(src, name):
    """The `"a" | "b" => Some("c")` arms of table `name`, as (names, runtime function)."""
    start = src.index(f"fn {name}(name: &str) -> Option<&'static str> {{")
    body = src[start:src.index("\n}\n", start)]
    found = re.findall(r'((?:"[^"]+"\s*\|?\s*)+)=>\s*Some\("([^"]+)"\)', body)
    rest = [l.strip() for l in body.split("\n") if "=>" in l and 'Some("' not in l]
    if len(rest) != 1 or not rest[0].startswith("_ =>"):
        sys.exit(f"{name}: an arm this script does not read: {rest}")
    return [(re.findall(r'"([^"]+)"', names), fn) for names, fn in found]


def render():
    with open(SOURCE, encoding="utf-8") as f:
        src = f.read()
    out = [
        "// Copyright (c) 2026 Jurjen Stellingwerff",
        "// SPDX-License-Identifier: LGPL-3.0-or-later",
        "",
        "// @generated by selfhost/bench/cgen_natives_gen.py from src/c/mod.rs — do not edit.",
        "//",
        "// @PLN91 strand 12 — the C generator in loft: the C runtime function that implements a",
        "// standard-library native (`native_c` with `host_native_c` and `json_native_c`), or null",
        "// for a name the runtime carries no function for.",
        "",
        "pub fn native_c(name: text) -> text? {",
        "  match name {",
    ]
    for table in TABLES:
        out.append(f"    // {table}")
        for names, fn in arms(src, table):
            out.append("    " + " | ".join(f'"{n}"' for n in names) + f' => "{fn}",')
    out += ["    _ => null,", "  }", "}", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the loft file is out of date")
    o = ap.parse_args()
    text = render()
    if o.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("selfhost/src/cgen_natives.loft is out of date: run selfhost/bench/cgen_natives_gen.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
